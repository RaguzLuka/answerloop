import type { NextConfig } from "next";

// Don't set turbopack.root here: pinning it to this folder made `next dev`
// respawn worker processes in a loop (hundreds of node processes). The
// "multiple lockfiles" warning it would silence is harmless.
const nextConfig: NextConfig = {
  // libSQL ships a native binding for local SQLite files — keep it out of the bundle
  serverExternalPackages: ["@libsql/client", "libsql"],
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
        ],
      },
      {
        source: "/sw.js",
        headers: [
          { key: "Content-Type", value: "application/javascript; charset=utf-8" },
          { key: "Cache-Control", value: "no-cache, no-store, must-revalidate" },
          { key: "Content-Security-Policy", value: "default-src 'self'; script-src 'self'" },
        ],
      },
    ];
  },
};

export default nextConfig;
